#!/bin/bash
# ============================================================
# 语义坐标发束测试脚本
# 用法:
#   1. 先启动 kigstudio.exe
#   2. 打开项目: C:\Users\cgoxo\Downloads\测试发束
#   3. 运行: bash scripts/test_semantic_hair.sh
#
# 测试流程:
#   a. 设置中心点 → 棕色箭头 + 矢状面三角出现
#   b. 配置坐标系（north_pole / front_reference）→ 坐标框架更新
#   c. 创建发束 → 获取新发束索引
#   d. 配置角度映射 → 经线/纬线 + 关键点可视化
#   e. 用语义坐标添加引导点和宽度点
# ============================================================

API="http://127.0.0.1:18920"
NODE_ADDON=1    # addon/hair 节点
NODE_BASE=0     # base mesh 节点

# ----- 颜色输出 -----
green() { echo -e "\033[32m$*\033[0m"; }
red()   { echo -e "\033[31m$*\033[0m"; }
blue()  { echo -e "\033[34m$*\033[0m"; }

# ----- 工具函数 -----
post() {
    local url="$1"; shift
    local data="$1"; shift
    local desc="$1"
    blue ">>> $desc"
    curl -s -X POST "$url" -H "Content-Type: application/json" -d "$data"
    echo ""
    echo ""
}

put() {
    local url="$1"; shift
    local data="$1"; shift
    local desc="$1"
    blue ">>> $desc"
    curl -s -X PUT "$url" -H "Content-Type: application/json" -d "$data"
    echo ""
    echo ""
}

get() {
    local url="$1"; shift
    local desc="$1"
    blue ">>> $desc"
    curl -s "$url"
    echo ""
    echo ""
}

# ============================================================
# Step 1: 检查服务器状态
# ============================================================
green "=============================================="
green "  Step 1: 检查服务器状态"
green "=============================================="
get "$API/api/v1/system/status" "检查系统状态" || {
    red "无法连接到 $API — 请先启动 kigstudio.exe 并打开项目"
    exit 1
}

# ============================================================
# Step 2: 设置添加器官定位点（显示中心点 = 触发调试可视化）
# ============================================================
green "=============================================="
green "  Step 2: 设置中心点"
green "  中心点可见时，若已配置角度映射，则显示调试可视化"
green "=============================================="
put "$API/api/v1/nodes/$NODE_ADDON/strands/center-point" \
    '{"show":true, "x":0.0, "y":0.0, "z":0.0}' \
    "设置中心点 (0,0,0) 并显示"

# ============================================================
# Step 3: 配置坐标系（北极 + 矢状面参考）
# ============================================================
green "=============================================="
green "  Step 3: 配置坐标系"
green "  north_pole       = [0, 1, 0]  (世界+Y, 默认北极)"
green "  front_reference  = [0, 0, 1]  (世界+Z, 默认矢状面)"
green "=============================================="
post "$API/api/v1/nodes/$NODE_ADDON/hair/angle-config" \
'{
  "base_node_id": 0,
  "north_pole": [0.0, 1.0, 0.0],
  "front_reference": [0.0, 0.0, 1.0],
  "angles": []
}' \
"设置默认坐标系（空角度映射）"

# 测试自定义坐标系：北极向前倾斜30°
green ">>> 测试自定义坐标系：北极向+Z倾斜30度"
post "$API/api/v1/nodes/$NODE_ADDON/hair/angle-config" \
'{
  "base_node_id": 0,
  "north_pole": [0.0, 0.866, 0.5],
  "front_reference": [1.0, 0.0, 0.0],
  "angles": []
}' \
"设置倾斜北极 [0, 0.866, 0.5] + 前参考 [1, 0, 0]"

# 恢复默认坐标系
green ">>> 恢复默认坐标系"
post "$API/api/v1/nodes/$NODE_ADDON/hair/angle-config" \
'{
  "base_node_id": 0,
  "north_pole": [0.0, 1.0, 0.0],
  "front_reference": [0.0, 0.0, 1.0],
  "angles": []
}' \
"恢复默认北极 [0, 1, 0] + 前参考 [0, 0, 1]"

# ============================================================
# Step 4: 先创建发束（避免后续 BVH 失效）
# ============================================================
green "=============================================="
green "  Step 4: 创建新发束"
green "=============================================="
STRAND_INDEX=$(curl -s -X POST "$API/api/v1/nodes/$NODE_ADDON/strands" \
    -H "Content-Type: application/json" \
    -d '{"name": "Semantic Test Strand"}' \
    | grep -o '"strand_index":[0-9]*' | grep -o '[0-9]*')
green "  新发束索引: $STRAND_INDEX"

# ============================================================
# Step 4: 配置语义坐标角度映射
# ============================================================
green "=============================================="
green "  Step 5: 配置语义坐标角度映射"
green "  north_pole    = [0, 1, 0]  (世界+Y)"
green "  front_reference = [0, 0, 1]  (世界+Z)"
green "=============================================="
post "$API/api/v1/nodes/$NODE_ADDON/hair/angle-config" \
'{
  "base_node_id": 0,
  "north_pole": [0.0, 1.0, 0.0],
  "front_reference": [0.0, 0.0, 1.0],
  "angles": [
    {"x": 0.0,  "y": 0.0,  "theta": 0,   "phi": 0},
    {"x": 30.0, "y": 0.0,  "theta": 30,  "phi": 0},
    {"x": -30.0,"y": 0.0,  "theta": -30, "phi": 0},
    {"x": 0.0,  "y": 30.0, "theta": 0,   "phi": 30},
    {"x": 0.0,  "y": -30.0,"theta": 0,   "phi": -30},
    {"x": 45.0, "y": 45.0,"theta": 45,   "phi": 45},
    {"x": -45.0,"y": 45.0,"theta": -45,  "phi": 45},
    {"x": 45.0, "y": -45.0,"theta": 45,  "phi": -45},
    {"x": -45.0,"y": -45.0,"theta": -45, "phi": -45}
  ]
}' \
"设置角度配置（9个采样点）"

# ============================================================
# Step 5: 添加语义引导点
# ============================================================
green "=============================================="
green "  Step 6: 添加语义引导点"
green "  → 发束 $STRAND_INDEX"
green "  利用配置的角度映射表，从中心点向模型表面投射射线"
green "=============================================="

for xy in \
    "0.0,0.0" \
    "10.0,0.0" \
    "20.0,0.0" \
    "30.0,0.0" \
    "40.0,0.0"
do
    x=$(echo "$xy" | cut -d, -f1)
    y=$(echo "$xy" | cut -d, -f2)
    post "$API/api/v1/nodes/$NODE_ADDON/strands/$STRAND_INDEX/guide-points/semantic" \
        "{\"x\": $x, \"y\": $y}" \
        "语义引导点 (x=$x, y=$y)"
done

# ============================================================
# Step 6: 添加语义宽度点
# ============================================================
green "=============================================="
green "  Step 7: 添加语义宽度点"
green "  → 发束 $STRAND_INDEX"
green "  投射射线获取模型表面点 → 计算到曲线投影 → 生成宽度向量"
green "=============================================="

for xy in \
    "10.0,5.0" \
    "20.0,8.0" \
    "30.0,5.0" \
    "10.0,-5.0" \
    "20.0,-8.0" \
    "30.0,-5.0"
do
    x=$(echo "$xy" | cut -d, -f1)
    y=$(echo "$xy" | cut -d, -f2)
    post "$API/api/v1/nodes/$NODE_ADDON/strands/$STRAND_INDEX/width-points/semantic" \
        "{\"x\": $x, \"y\": $y}" \
        "语义宽度点 (x=$x, y=$y)"
done

# ============================================================
# Step 7: 查看最终结果
# ============================================================
green "=============================================="
green "  Step 8: 查看最终发束数据"
green "=============================================="
get "$API/api/v1/nodes/$NODE_ADDON/strands/$STRAND_INDEX" \
    "查看发束 $STRAND_INDEX 的完整数据"

green "=============================================="
green "  测试完成！"
green "  请观察 3D 视口中是否出现："
green "    1. 棕色箭头（指向北极方向 [0,1,0]）"
green "    2. 中心点处的等腰直角三角形（矢状面）"
green "       - 一直角边沿北极"
green "       - 一直角边沿鼻尖方向 [0,0,1]"
green "    3. 新创建的发束网格"
green "=============================================="

# ============================================================
# (可选) 倾斜北极测试
# 取消下方注释后运行，可看到箭头和三角随北极旋转
# ============================================================
: <<'COMMENT'
green "=============================================="
green "  Bonus: 测试倾斜北极 + 自定义矢状面"
green "  north_pole 向 +Z 倾斜 30 度"
green "  front_reference 指向 +X"
green "=============================================="
post "$API/api/v1/nodes/$NODE_ADDON/hair/angle-config" \
'{
  "base_node_id": 0,
  "north_pole": [0.0, 0.866, 0.5],
  "front_reference": [1.0, 0.0, 0.0],
  "angles": [
    {"x": 0.0, "y": 0.0, "theta": 0, "phi": 0},
    {"x": 30.0, "y": 0.0, "theta": 30, "phi": 0},
    {"x": -30.0, "y": 0.0, "theta": -30, "phi": 0},
    {"x": 0.0, "y": 30.0, "theta": 0, "phi": 30},
    {"x": 0.0, "y": -30.0, "theta": 0, "phi": -30}
  ]
}' \
"设置倾斜北极 [0, 0.866, 0.5] + 前参考 [1, 0, 0]"
COMMENT
